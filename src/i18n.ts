export const messages: Record<ProductLocale, Record<MessageKey, string>> = { ja: jaMessages, en: enMessages };
const requestedLocale = import.meta.env?.VITE_PRODUCT_LOCALE;
export const ACTIVE_PRODUCT_LOCALE: ProductLocale = requestedLocale === 'en' ? 'en' : 'ja';

export function message(locale: ProductLocale, key: MessageKey, values: Record<string, string | number> = {}) {
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), messages[locale][key]);
}

export const t = (key: MessageKey, values?: Record<string, string | number>) => message(ACTIVE_PRODUCT_LOCALE, key, values);
